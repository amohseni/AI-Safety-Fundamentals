// Writes docs/js/pages.js, the list of all pages, from specs/ and docs/pages/.
// A page counts as built when docs/pages/<id with dot replaced by dash>.html exists.
// Run after adding a page: node tools/build-registry.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const specs = path.join(root, 'specs');
const CORE = ['1.1', '2.1', '2.4', '2.5', '2.6', '2.7', '3.3', '3.4', '3.6', '4.1', '4.3', '5.2', '5.5', '6.2', '6.4', '6.7', '7.1', '8.1', '8.2', '8.4', '8.5'];

const sections = [];
const bank = {};
for (const dir of fs.readdirSync(specs).filter((d) => /^\d-/.test(d)).sort()) {
  const readme = fs.readFileSync(path.join(specs, dir, 'README.md'), 'utf8');
  const h1 = readme.match(/^#\s+(\d)\s+(.+)$/m);
  const pages = [];
  for (const f of fs.readdirSync(path.join(specs, dir)).filter((f) => /^\d\.\d/.test(f)).sort((a, b) => parseFloat(a) - parseFloat(b))) {
    const text = fs.readFileSync(path.join(specs, dir, f), 'utf8');
    const m = text.match(/^##\s+(\d\.\d)\s+(.+)$/m);
    const id = m[1];
    const file = `pages/${id.replace('.', '-')}.html`;
    const built = fs.existsSync(path.join(root, 'docs', file));
    // The page's check questions: ids and correct options go in the page list (progress is worked
    // out from them); the full questions go in docs/data/checks.json for the review blocks.
    const checks = [];
    if (built) {
      const html = fs.readFileSync(path.join(root, 'docs', file), 'utf8');
      const re = /<div class="check" data-id="([^"]+)" data-correct="(\d+)">([\s\S]*?)<div class="feedback">([\s\S]*?)<\/div>\s*<\/div>/g;
      for (const c of html.matchAll(re)) {
        const q = c[3].match(/<p class="q">([\s\S]*?)<\/p>/)[1].trim();
        const options = [...c[3].matchAll(/<button>([\s\S]*?)<\/button>/g)].map((o) => o[1]);
        const correct = Number(c[2]);
        if (!(correct < options.length)) throw new Error(`${c[1]}: data-correct out of range`);
        const fb = [...c[4].matchAll(/<p>([\s\S]*?)<\/p>/g)].map((x) => x[1].trim()).join('</p><p>');
        checks.push([c[1], correct]);
        // A question that refers to its own page's tool or text cannot be asked elsewhere.
        if (!/\b(in the tool|this page|above|below)\b/i.test(q)) bank[c[1]] = { q, options, correct, feedback: fb };
      }
    }
    pages.push({ id, title: m[2].trim(), core: CORE.includes(id), href: built ? file : null, checks });
  }
  sections.push({ n: Number(h1[1]), title: h1[2].trim(), pages });
}
const out = `// Generated by tools/build-registry.mjs. Do not edit by hand.\nexport const sections = ${JSON.stringify(sections, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'docs', 'js', 'pages.js'), out);
fs.writeFileSync(path.join(root, 'docs', 'data', 'checks.json'), JSON.stringify(bank));
console.log(`${Object.keys(bank).length} check questions available for review`);
console.log(sections.map((s) => `${s.n} ${s.title}: ${s.pages.length} pages, ${s.pages.filter((p) => p.href).length} built`).join('\n'));

// Keep the site map (page 0.1) in step with the page list.
const sitemap = path.join(root, 'tools', 'build-sitemap.mjs');
if (fs.existsSync(sitemap)) await import(sitemap);
