// Writes docs/js/pages.js, the list of all pages, from specs/ and docs/pages/.
// A page counts as built when docs/pages/<id with dot replaced by dash>.html exists.
// Run after adding a page: node tools/build-registry.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const specs = path.join(root, 'specs');
const CORE = ['1.1', '2.1', '2.4', '2.5', '2.6', '2.7', '3.4', '3.6', '4.1', '4.3', '5.2', '5.5', '6.2', '6.4', '6.7', '7.1', '8.1', '8.2', '8.4', '8.5'];

const sections = [];
for (const dir of fs.readdirSync(specs).filter((d) => /^\d-/.test(d)).sort()) {
  const readme = fs.readFileSync(path.join(specs, dir, 'README.md'), 'utf8');
  const h1 = readme.match(/^#\s+(\d)\s+(.+)$/m);
  const pages = [];
  for (const f of fs.readdirSync(path.join(specs, dir)).filter((f) => /^\d\.\d/.test(f)).sort((a, b) => parseFloat(a) - parseFloat(b))) {
    const text = fs.readFileSync(path.join(specs, dir, f), 'utf8');
    const m = text.match(/^##\s+(\d\.\d)\s+(.+)$/m);
    const id = m[1];
    const file = `pages/${id.replace('.', '-')}.html`;
    pages.push({ id, title: m[2].trim(), core: CORE.includes(id), href: fs.existsSync(path.join(root, 'docs', file)) ? file : null });
  }
  sections.push({ n: Number(h1[1]), title: h1[2].trim(), pages });
}
const out = `// Generated by tools/build-registry.mjs. Do not edit by hand.\nexport const sections = ${JSON.stringify(sections, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'docs', 'js', 'pages.js'), out);
console.log(sections.map((s) => `${s.n} ${s.title}: ${s.pages.length} pages, ${s.pages.filter((p) => p.href).length} built`).join('\n'));
